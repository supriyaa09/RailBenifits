export type RELHSSubscriptionBand = (typeof RELHS_RULES.subscriptionBands)[number];
export type CommutationFactorRow = (typeof COMMUTATION_FACTORS)[number];

export function findRELHSSubscriptionBand(level: number): RELHSSubscriptionBand | null {
  return (
    RELHS_RULES.subscriptionBands.find((band) => {
      const withinLowerBound = level >= band.minLevel;
      const withinUpperBound = band.maxLevel === null || level <= band.maxLevel;
      return withinLowerBound && withinUpperBound;
    }) ?? null
  );
}

export function findDeathGratuitySlab(serviceYears: number) {
  return (
    GRATUITY_RULES.deathSlabs.find(
      (slab) => serviceYears >= slab.minYears && serviceYears < slab.maxYearsExclusive,
    ) ?? null
  );
}

export function toPercent(rate: number): number {
  return rate * 100;
}
